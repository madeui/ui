test('imports go after a leading directive; Vite statements go after imports that follow a block comment', () => {
  write('lib/themes.ts', THEMES);
  write('app/layout.tsx', `'use client';\n\nexport default function RootLayout({ children }) {\n  return (\n    <html>\n      <body>{children}</body>\n    </html>\n  );\n}\n`);
  write('src/lib/themes.ts', THEMES);
  write('src/main.tsx', `/* Entry */\nimport './index.css'\n\nrender()\n`);

  applyPageStyles(cwd, 'next', 'lib', []);
  applyPageStyles(cwd, 'vite', 'src/lib', []);

  expect(read('app/layout.tsx')).toMatch(/^'use client';\nimport \* as stylex/);
  expect(read('src/main.tsx')).toMatch(
    /^\/\* Entry \*\/\nimport '.\/index.css'\nimport \* as stylex from '@stylexjs\/stylex'\nimport \{ colorScheme, page \} from '.\/lib\/themes'\n\n\/\/ Page styles/
  );
});

