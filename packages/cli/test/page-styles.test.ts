test('Vite: adds the classes to <html> and <body> from the create-vite entry', () => {
  write('src/lib/themes.ts', THEMES);
  write(
    'src/main.tsx',
    `import { StrictMode } from 'react'
import { createRoot } from 'react-dom/client'
import './index.css'
import App from './App.tsx'

createRoot(document.getElementById('root')!).render(
  <StrictMode>
    <App />
  </StrictMode>,
)
`
  );
  const changed: string[] = [];

  expect(applyPageStyles(cwd, 'vite', 'src/lib', changed)).toEqual([]);
  expect(changed).toEqual(['src/main.tsx']);
  expect(read('src/main.tsx')).toBe(`import { StrictMode } from 'react'
import { createRoot } from 'react-dom/client'
import './index.css'
import App from './App.tsx'
import * as stylex from '@stylexjs/stylex'
import { colorScheme, page } from './lib/themes'

// Page styles from lib/themes.ts: colorScheme on <html>, page on <body>.
document.documentElement.classList.add(...(stylex.props(colorScheme).className?.split(' ') ?? []))
document.body.classList.add(...(stylex.props(page).className?.split(' ') ?? []))

createRoot(document.getElementById('root')!).render(
  <StrictMode>
    <App />
  </StrictMode>,
)
`);

  applyPageStyles(cwd, 'vite', 'src/lib', changed);
  expect(changed).toEqual(['src/main.tsx']);
});

