import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import { afterEach, beforeEach, expect, test, vi } from 'vitest';

import { applyPageStyles } from '../src/page-styles.ts';

const THEMES = 'export const colorScheme = {};\nexport const page = {};\n';

// create-next-app 16 `app` template.
const NEXT_LAYOUT = `import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html lang="en" className={\`\${geistSans.variable} \${geistMono.variable}\`}>
      <body>{children}</body>
    </html>
  );
}
`;

let cwd: string;
const read = (rel: string) => fs.readFileSync(path.join(cwd, rel), 'utf8');
const write = (rel: string, content: string) => {
  fs.mkdirSync(path.dirname(path.join(cwd, rel)), { recursive: true });
  fs.writeFileSync(path.join(cwd, rel), content);
};

beforeEach(() => {
  cwd = fs.mkdtempSync(path.join(os.tmpdir(), 'madeui-layout-'));
  vi.spyOn(console, 'log').mockImplementation(() => {});
});

afterEach(() => {
  vi.restoreAllMocks();
  fs.rmSync(cwd, { recursive: true, force: true });
});

test('Next: puts colorScheme on <html> and page on <body> in the create-next-app layout', () => {
  write('lib/themes.ts', THEMES);
  write('app/layout.tsx', NEXT_LAYOUT);
  const changed: string[] = [];

  const steps = applyPageStyles(cwd, 'next', 'lib', changed);

  expect(steps).toEqual([]);
  expect(changed).toEqual(['app/layout.tsx']);
  const layout = read('app/layout.tsx');
  expect(layout).toContain(
    `import "./globals.css";\nimport * as stylex from "@stylexjs/stylex";\nimport { colorScheme, page } from "../lib/themes";\n`
  );
  expect(layout).toContain(
    '<html lang="en" className={`${geistSans.variable} ${geistMono.variable} ${stylex.props(colorScheme).className}`}>'
  );
  expect(layout).toContain('<body {...stylex.props(page)}>{children}</body>');
});

test('imports through the "@/*" path alias when tsconfig maps it over the lib folder', () => {
  write('lib/themes.ts', THEMES);
  write('app/layout.tsx', NEXT_LAYOUT);
  write('tsconfig.json', '{\n  "compilerOptions": {\n    // comment\n    "paths": {\n      "@/*": ["./*"]\n    }\n  }\n}\n');
  write('src/lib/themes.ts', THEMES);
  write('src/main.tsx', "import './index.css'\n");
  write('tsconfig.app.json', '{ "compilerOptions": { "paths": { "@/*": ["./src/*"] } } }\n');

  applyPageStyles(cwd, 'next', 'lib', []);
  applyPageStyles(cwd, 'vite', 'src/lib', []);

  expect(read('app/layout.tsx')).toContain('import { colorScheme, page } from "@/lib/themes";');
  expect(read('src/main.tsx')).toContain("import { colorScheme, page } from '@/lib/themes'");
});

